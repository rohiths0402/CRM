import { RIDER_TEMPLATES } from "../constants/lineup";

export const buildRiderItems = (slotId, progress = 0) => {
  const done = Math.floor(RIDER_TEMPLATES.length * progress);

  return RIDER_TEMPLATES.map((template, index) => {
    let status = "PENDING";
    if (index < done) status = "READY";
    else if (index === done && progress > 0) status = "CONFIRMED";

    return {
      id: slotId * 100 + index + 1,
      label: template.label,
      category: template.category,
      status,
    };
  });
};

const makeSlot = ({ core, manager, notes, progress }) => {
  const [
    id,
    eventId,
    artistName,
    role,
    stage,
    start,
    end,
    soundcheck,
    greenRoom,
    status,
    fee,
    advancePaid,
  ] = core;
  const [managerName, managerPhone, managerEmail] = manager;
  const [dietaryNotes, soundRigNotes, securityNotes, escortRequired] =
    notes || ["", "", "", false];

  return {
    id,
    eventId,
    artistName,
    role,
    stage,
    start,
    end,
    soundcheck,
    greenRoom,
    status,
    fee,
    advancePaid,
    managerName,
    managerPhone,
    managerEmail,
    dietaryNotes,
    soundRigNotes,
    securityNotes,
    escortRequired,
    riderItems: buildRiderItems(id, progress),
  };
};

