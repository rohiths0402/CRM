const SALES_BIAS = [1.3, 1.15, 1, 0.8];

const spreadSales = (total, capacities) => {
  const sold = capacities.map(() => 0);
  let left = total;
  let open = capacities.map((_, index) => index);

  while (left > 0 && open.length) {
    const weight = open.reduce(
      (sum, index) => sum + capacities[index] * SALES_BIAS[index],
      0,
    );
    let given = 0;

    open.forEach((index) => {
      const room = capacities[index] - sold[index];
      const share = Math.min(
        room,
        Math.floor((left * capacities[index] * SALES_BIAS[index]) / weight),
      );
      sold[index] += share;
      given += share;
    });

    left -= given;
    open = open.filter((index) => sold[index] < capacities[index]);

    if (given === 0 && open.length) {
      sold[open[0]] += 1;
      left -= 1;
    }
  }

  return sold;
};

const buildZones = (venueId, capacity, soldTotal, statuses = []) => {
  const capacities = ZONE_BLUEPRINT.map((zone) =>
    Math.round(capacity * zone.share),
  );
  capacities[3] += capacity - capacities.reduce((sum, value) => sum + value, 0);
  const sold = spreadSales(soldTotal, capacities);

  return ZONE_BLUEPRINT.map((zone, index) => ({
    id: venueId * 10 + index + 1,
    name: zone.name,
    kind: zone.kind,
    capacity: capacities[index],
    sold: sold[index],
    fireExits: zone.fireExits,
    safetyStatus: statuses[index] || "VERIFIED",
    lastInspection: "2026-10-12",
  }));
};

